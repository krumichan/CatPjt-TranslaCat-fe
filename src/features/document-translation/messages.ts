/** 문서 번역 문구를 현재 locale에 맞춰 선택하며 학습 모드는 일본어를 사용한다. */
export function getDocumentTranslationCopy(locale: string): DocumentTranslationCopy {
    if (locale === "ko") {
        return ko;
    }
    return locale === "ja" || locale === "learning" ? ja : en;
}

/** 알려진 API 코드만 번역해서 보여 주며 서버의 오류 본문은 표시하지 않는다. */
export function documentErrorMessage(copy: DocumentTranslationCopy, code: string): string {
    return Object.hasOwn(copy.errors, code)
        ? copy.errors[code as keyof typeof copy.errors]
        : copy.genericError;
}
