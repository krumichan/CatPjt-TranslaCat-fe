export type GuideHelpTopic = keyof typeof guideHelpTopics;
export type GuideHelpLocale = "ko" | "ja" | "en";

export function getGuideHelpLocale(locale: string): GuideHelpLocale {
    if (locale === "en") return "en";
    if (locale === "ja" || locale === "learning") return "ja";
    return "ko";
}

export function getGuideHelpTarget(topic: GuideHelpTopic, locale: string) {
    // 앱의 학습 모드는 기존 동선과 같이 일본어 문서로 연결한다.
    const guideLocale = getGuideHelpLocale(locale);
    const suffix = topic === "index" ? "" : "/" + topic;

    return {
        href: "/" + guideLocale + "/docs" + suffix,
        title: guideHelpTopics[topic][guideLocale],
    };
}
